// 일반 성적 파싱 데이터 가져오기
export const fetchParsedScoreRows = async (
    studentId: string
): Promise<ScoreRowData[]> => {
    const res = await fetch(`${process.env.API_URL}/api/score-rows/${studentId}`);
    if (!res.ok) throw new Error("성적 파싱 데이터 요청 실패");
    return res.json();
};

// 모의고사 점수 가져오기
export const fetchMockTestResults = async (
    studentId: string
): Promise<StudentMockTestData> => {
    const res = await fetch(`${process.env.API_URL}/api/mock-tests/${studentId}`);
    if (!res.ok) throw new Error("모의고사 데이터 요청 실패");
    return res.json();
};

